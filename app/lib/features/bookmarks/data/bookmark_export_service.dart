import 'dart:convert';
import '../domain/bookmark_models.dart';

/// Supported export formats for intra-media bookmarks and annotations.
enum BookmarkExportFormat {
  json,
  vlcXspf,
  markdown,
  csv,
  ffmpegChapters,
  srt,
}

/// Service handling serialization, export, and import of media bookmarks across
/// multiple standard industry formats including VLC XSPF, FFmpeg metadata, and Markdown.
class BookmarkExportService {
  /// Converts a list of [bookmarks] into the specified [format] string representation.
  static String exportToString(
    List<MediaBookmark> bookmarks,
    BookmarkExportFormat format, {
    String? mediaTitle,
  }) {
    final title = mediaTitle ?? 'Media';

    switch (format) {
      case BookmarkExportFormat.json:
        return _exportJson(bookmarks, title);
      case BookmarkExportFormat.vlcXspf:
        return _exportVlcXspf(bookmarks, title);
      case BookmarkExportFormat.markdown:
        return _exportMarkdown(bookmarks, title);
      case BookmarkExportFormat.csv:
        return _exportCsv(bookmarks);
      case BookmarkExportFormat.ffmpegChapters:
        return _exportFfmpegChapters(bookmarks, title);
      case BookmarkExportFormat.srt:
        return _exportSrt(bookmarks);
    }
  }

  /// Parses an imported string in either JSON or CSV format and reconstructs [MediaBookmark]s.
  static List<MediaBookmark> importFromString(
    String content, {
    required String mediaId,
  }) {
    final trimmed = content.trim();
    if (trimmed.isEmpty) return [];

    // Attempt JSON parsing first
    if (trimmed.startsWith('{') || trimmed.startsWith('[')) {
      try {
        final decoded = json.decode(trimmed);
        List<dynamic> items = [];
        if (decoded is List) {
          items = decoded;
        } else if (decoded is Map<String, dynamic>) {
          if (decoded['bookmarks'] is List) {
            items = decoded['bookmarks'] as List<dynamic>;
          }
        }

        return items.map((raw) {
          final map = Map<String, dynamic>.from(raw as Map);
          map['mediaId'] = mediaId;
          return MediaBookmark.fromJson(map);
        }).toList();
      } catch (_) {
        // Fall through to CSV parser
      }
    }

    // CSV parsing fallback
    return _importCsv(trimmed, mediaId);
  }

  // --- EXPORT FORMAT ENGINES ---

  static String _exportJson(List<MediaBookmark> bookmarks, String mediaTitle) {
    final map = {
      'format': 'eplayer_bookmarks_v1',
      'mediaTitle': mediaTitle,
      'exportedAt': DateTime.now().toIso8601String(),
      'count': bookmarks.length,
      'bookmarks': bookmarks.map((b) => b.toJson()).toList(),
    };
    const encoder = JsonEncoder.withIndent('  ');
    return encoder.convert(map);
  }

  static String _exportVlcXspf(List<MediaBookmark> bookmarks, String mediaTitle) {
    final buffer = StringBuffer();
    buffer.writeln('<?xml version="1.0" encoding="UTF-8"?>');
    buffer.writeln('<playlist version="1" xmlns="http://xspf.org/ns/0/" xmlns:vlc="http://www.videolan.org/vlc/playlist/0">');
    buffer.writeln('  <title>Bookmarks: ${_escapeXml(mediaTitle)}</title>');
    buffer.writeln('  <trackList>');
    buffer.writeln('    <track>');
    buffer.writeln('      <title>${_escapeXml(mediaTitle)}</title>');
    buffer.writeln('      <extension application="http://www.videolan.org/vlc/playlist/0">');
    buffer.writeln('        <vlc:node title="bookmarks">');

    for (final bm in bookmarks) {
      final seconds = (bm.position.inMicroseconds / 1e6).round();
      final name = _escapeXml(bm.label);
      final desc = _escapeXml(bm.note ?? '');
      buffer.writeln('          <vlc:item time="$seconds" name="$name" description="$desc" />');
    }

    buffer.writeln('        </vlc:node>');
    buffer.writeln('      </extension>');
    buffer.writeln('    </track>');
    buffer.writeln('  </trackList>');
    buffer.writeln('</playlist>');
    return buffer.toString();
  }

  static String _exportMarkdown(List<MediaBookmark> bookmarks, String mediaTitle) {
    final buffer = StringBuffer();
    buffer.writeln('# Bookmarks & Annotations: $mediaTitle');
    buffer.writeln();
    buffer.writeln('> Generated by E-Player on ${DateTime.now().toIso8601String().split('T').first}');
    buffer.writeln();

    for (var i = 0; i < bookmarks.length; i++) {
      final bm = bookmarks[i];
      final tag = bm.category.isNotEmpty && bm.category != 'general'
          ? ' `[${bm.category.toUpperCase()}]`'
          : '';
      buffer.writeln('- **[${bm.formattedRange}]** ${bm.label}$tag');
      if (bm.note != null && bm.note!.trim().isNotEmpty) {
        buffer.writeln('  > ${bm.note!.trim().replaceAll('\n', '\n  > ')}');
      }
    }
    return buffer.toString();
  }

  static String _exportCsv(List<MediaBookmark> bookmarks) {
    final buffer = StringBuffer();
    buffer.writeln('TimestampMs,Time,EndTime,Label,Category,Notes');
    for (final bm in bookmarks) {
      final end = bm.formattedEndTime ?? '';
      final note = bm.note != null ? _escapeCsv(bm.note!) : '';
      final label = _escapeCsv(bm.label);
      buffer.writeln('${bm.timestampMs},${bm.formattedTime},$end,$label,${bm.category},$note');
    }
    return buffer.toString();
  }

  static String _exportFfmpegChapters(List<MediaBookmark> bookmarks, String mediaTitle) {
    final buffer = StringBuffer();
    buffer.writeln(';FFMETADATA1');
    buffer.writeln('title=${_escapeFfmpeg(mediaTitle)}');
    buffer.writeln();

    for (var i = 0; i < bookmarks.length; i++) {
      final bm = bookmarks[i];
      final startMs = bm.timestampMs;
      final endMs = bm.endTimestampMs ??
          (i < bookmarks.length - 1
              ? bookmarks[i + 1].timestampMs
              : startMs + 10000); // 10s default chapter window

      buffer.writeln('[CHAPTER]');
      buffer.writeln('TIMEBASE=1/1000');
      buffer.writeln('START=$startMs');
      buffer.writeln('END=$endMs');
      buffer.writeln('title=${_escapeFfmpeg(bm.label)}');
      if (bm.note != null && bm.note!.isNotEmpty) {
        buffer.writeln('comment=${_escapeFfmpeg(bm.note!)}');
      }
      buffer.writeln();
    }
    return buffer.toString();
  }

  static String _exportSrt(List<MediaBookmark> bookmarks) {
    final buffer = StringBuffer();
    for (var i = 0; i < bookmarks.length; i++) {
      final bm = bookmarks[i];
      final cueIndex = i + 1;
      final startTime = _formatSrtTimestamp(bm.position);
      final endTime = _formatSrtTimestamp(
        bm.endPosition ?? bm.position + const Duration(seconds: 5),
      );

      buffer.writeln('$cueIndex');
      buffer.writeln('$startTime --> $endTime');
      buffer.writeln('[${bm.label}]');
      if (bm.note != null && bm.note!.trim().isNotEmpty) {
        buffer.writeln(bm.note!.trim());
      }
      buffer.writeln();
    }
    return buffer.toString();
  }

  // --- CSV IMPORT HELPER ---

  static List<MediaBookmark> _importCsv(String csvContent, String mediaId) {
    final lines = csvContent.split('\n');
    if (lines.length < 2) return [];

    final result = <MediaBookmark>[];
    for (var i = 1; i < lines.length; i++) {
      final line = lines[i].trim();
      if (line.isEmpty) continue;
      final parts = _parseCsvLine(line);
      if (parts.length < 4) continue;

      final tsMs = int.tryParse(parts[0]) ?? 0;
      final label = parts[3];
      final category = parts.length > 4 && parts[4].isNotEmpty ? parts[4] : 'general';
      final note = parts.length > 5 && parts[5].isNotEmpty ? parts[5] : null;

      result.add(
        MediaBookmark(
          id: 'imp_${DateTime.now().microsecondsSinceEpoch}_$i',
          mediaId: mediaId,
          position: Duration(milliseconds: tsMs),
          label: label,
          category: category,
          note: note,
          createdAt: DateTime.now(),
        ),
      );
    }
    return result;
  }

  static List<String> _parseCsvLine(String line) {
    final values = <String>[];
    final sb = StringBuffer();
    bool insideQuotes = false;

    for (var i = 0; i < line.length; i++) {
      final char = line[i];
      if (char == '"') {
        if (insideQuotes && i + 1 < line.length && line[i + 1] == '"') {
          sb.write('"');
          i++; // skip escaped quote
        } else {
          insideQuotes = !insideQuotes;
        }
      } else if (char == ',' && !insideQuotes) {
        values.add(sb.toString().trim());
        sb.clear();
      } else {
        sb.write(char);
      }
    }
    values.add(sb.toString().trim());
    return values;
  }

  // --- FORMATTING UTILS ---

  static String _formatSrtTimestamp(Duration d) {
    final hours = d.inHours.toString().padLeft(2, '0');
    final minutes = d.inMinutes.remainder(60).toString().padLeft(2, '0');
    final seconds = d.inSeconds.remainder(60).toString().padLeft(2, '0');
    final millis = d.inMilliseconds.remainder(1000).toString().padLeft(3, '0');
    return '$hours:$minutes:$seconds,$millis';
  }

  static String _escapeXml(String text) {
    return text
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&apos;');
  }

  static String _escapeCsv(String text) {
    if (text.contains(',') || text.contains('"') || text.contains('\n')) {
      return '"${text.replaceAll('"', '""')}"';
    }
    return text;
  }

  static String _escapeFfmpeg(String text) {
    return text
        .replaceAll('=', '\\=')
        .replaceAll(';', '\\;')
        .replaceAll('#', '\\#')
        .replaceAll('\\', '\\\\')
        .replaceAll('\n', ' ');
  }
}
